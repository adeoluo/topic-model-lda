"""A deterministic scale benchmark for LDA Gibbs-sampling throughput.

Runs collapsed Gibbs sampling over progressively larger synthetic document
collections (generated by ``data.documents``) at a fixed iteration count. For
each workload it reports wall-clock seconds, training throughput in documents
per second, peak memory in MiB measured with the standard-library ``tracemalloc``
module, and mean UMass topic coherence as the quality metric.

Timing is measured without tracemalloc (which otherwise slows every allocation);
peak memory is traced separately around the corpus, the model construction, and
a single sweep, which is faithful because the token assignments and count
matrices are allocated up front and reused each iteration rather than growing.
The documents are synthetic, drawn from three clear themes. This pure-Python
from-scratch implementation is not competitive on wall-clock time with compiled
topic-model libraries; the goal is to show how Gibbs sampling scales with the
number of documents. Deterministic and offline; run with:

    uv run python benchmarks/scale.py
"""

from __future__ import annotations

import time
import tracemalloc
from dataclasses import dataclass

from topic_model_lda.corpus import Corpus
from topic_model_lda.data import documents
from topic_model_lda.evaluation import topic_coherence
from topic_model_lda.lda import LDA, LDAConfig

WORKLOAD_SIZES: tuple[int, ...] = (200, 400, 800, 1600)
ITERATIONS = 80
NUM_TOPICS = 3
_BYTES_PER_MIB = 1024 * 1024


@dataclass(frozen=True)
class ScaleRow:
    """One measured workload: size, timing, throughput, memory, and quality."""

    size: int
    seconds: float
    throughput: float
    peak_mib: float
    coherence: float


def _config(iterations: int) -> LDAConfig:
    return LDAConfig(num_topics=NUM_TOPICS, iterations=iterations, seed=0)


def _peak_mib(size: int) -> float:
    """Peak memory to hold ``size`` documents, build the model, and run one sweep.

    Gibbs sampling allocates its token assignments and count matrices at
    construction and reuses them every iteration, so a corpus plus one sweep is
    a faithful peak without tracing the whole training run under tracemalloc.
    """

    tracemalloc.start()
    tracemalloc.reset_peak()
    corpus = Corpus.from_texts(documents(count=size, seed=0))
    model = LDA(corpus, _config(iterations=1))
    model.train()
    _, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return peak / _BYTES_PER_MIB


def run_scale(sizes: tuple[int, ...] = WORKLOAD_SIZES) -> list[ScaleRow]:
    """Measure Gibbs-sampling scaling across document counts."""

    rows: list[ScaleRow] = []
    for size in sizes:
        corpus = Corpus.from_texts(documents(count=size, seed=0))
        model = LDA(corpus, _config(ITERATIONS))
        start = time.perf_counter()
        model.train()
        elapsed = time.perf_counter() - start
        report = topic_coherence(model, corpus)
        rows.append(
            ScaleRow(
                size=size,
                seconds=elapsed,
                throughput=size / elapsed if elapsed else 0.0,
                peak_mib=_peak_mib(size),
                coherence=report.mean,
            )
        )
    return rows


def main() -> None:
    print("Synthetic three-theme documents; from-scratch collapsed Gibbs LDA.")
    print("Pure-Python sampling; not benchmarked against compiled topic-model libraries.")
    print(f"{'documents':>10}  {'seconds':>9}  {'docs/sec':>9}  {'peak MiB':>9}  {'coherence':>10}")
    for row in run_scale():
        print(
            f"{row.size:>10d}  {row.seconds:>9.3f}  {row.throughput:>9.1f}  "
            f"{row.peak_mib:>9.2f}  {row.coherence:>10.3f}"
        )


if __name__ == "__main__":
    main()
